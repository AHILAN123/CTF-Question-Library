#!/usr/bin/env python3
"""Encrypt the compiled part3 under a fresh AES-128 key (K2) and emit
part2_gen.h with the embedded blob + obfuscated key material. Writes K2 (hex)
to --key-out for the build self-test (never shipped)."""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import aeslib

PART2_FLAG = "flag{PART2_4nt1_d3bug_wr4pp3r_byp4ss3d}"


def carr(name, b):
    return "const unsigned char %s[%d] = {%s};" % (
        name, len(b), ",".join("0x%02x" % x for x in b))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--part3", required=True)
    ap.add_argument("--out-header", required=True)
    ap.add_argument("--key-out", required=True)
    ap.add_argument("--flag", default=PART2_FLAG)
    a = ap.parse_args()

    data = open(a.part3, "rb").read()
    K2 = os.urandom(16)
    IV = os.urandom(16)
    blob = IV + aeslib.encrypt_cbc(K2, IV, data)
    mask = os.urandom(16)
    obf = bytes(x ^ y for x, y in zip(K2, mask))
    garbage = os.urandom(16)
    flag = a.flag.encode()
    fenc = bytes(flag[i] ^ K2[i % 16] ^ ((i * 7) & 0xFF) for i in range(len(flag)))

    with open(a.out_header, "w") as f:
        f.write("/* AUTO-GENERATED by tools/make_part2_gen.py -- do not edit. */\n")
        f.write("#ifndef PART2_GEN_H\n#define PART2_GEN_H\n")
        f.write(carr("enc_blob", blob) + "\n")
        f.write("const unsigned int enc_blob_len = %d;\n" % len(blob))
        f.write(carr("k2_obf", obf) + "\n")
        f.write(carr("k2_mask", mask) + "\n")
        f.write(carr("keycorrupt_garbage", garbage) + "\n")
        f.write(carr("part2_flag_enc", fenc) + "\n")
        f.write("const unsigned int part2_flag_len = %d;\n" % len(flag))
        f.write("#endif\n")
    open(a.key_out, "w").write(K2.hex() + "\n")
    print("[make_part2_gen] part3=%d B, blob=%d B, K2->%s" % (len(data), len(blob), a.key_out))


if __name__ == "__main__":
    main()
